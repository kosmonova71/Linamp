def source_text() -> str:
    """Return the source of every module in this package.

    A number of regression tests assert on the renderer's source text.
    The renderer used to be a single module, so those tests could simply
    read ``milkdrop_renderer.__file__``; now that the implementation is
    split across the package they read the concatenated package source
    instead.
    """
    package_dir = Path(__file__).resolve().parent
    return "\n".join(
        path.read_text(encoding="utf-8") for path in sorted(package_dir.glob("*.py"))
    )


