"""MilkDrop renderer package.

The renderer used to live in a single 15k line module.  It is now split
into focused submodules:

* :mod:`renderer.config` - shared constants, limits and helpers
* :mod:`renderer.gl` - uniform and GL helper types
* :mod:`renderer.budgets` - evaluation budget types
* :mod:`renderer.textures` - texture cache and async texture loading
* :mod:`renderer.profiling` - frame profiling helpers
* :mod:`renderer.state` - preset variable state
* :mod:`renderer.shaders` - MilkDrop expression compiler (GLSL + bytecode)
* :mod:`renderer.presets` - preset parsing, VM and compilation cache
* :mod:`renderer.recovery` - renderer recovery state machine
* :mod:`renderer.evolution` - sprite/effect graph, fitness and evolution
* :mod:`renderer.passes` - render graph passes (feedback, waves, composite)
* :mod:`renderer.core` - the ``MilkdropRenderer`` widget

``milkdrop_renderer`` remains as a thin compatibility shim so existing
imports keep working.
"""

